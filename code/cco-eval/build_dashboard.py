#!/usr/bin/env python3
"""Build the Waterloo admission dashboard and print the suite metric."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from collections import Counter
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROBLEMS = ROOT / "problems"
DEFAULT_DASHBOARD = ROOT / "reports/DASHBOARD.md"
DASHBOARD_PATH = "reports/DASHBOARD.md"


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _records(problems_root: Path) -> list[dict[str, Any]]:
    report_path = problems_root / "admission-report.json"
    try:
        report = _read_json(report_path) if report_path.is_file() else {}
    except (OSError, json.JSONDecodeError):
        report = {}
    conflicts = {
        item.get("problem_id"): item.get("detail", "sample check conflict")
        for item in report.get("sample_conflicts", [])
        if isinstance(item, dict) and item.get("problem_id")
    }
    rows = []
    for status_path in sorted(problems_root.glob("*/status.json")):
        problem_dir = status_path.parent
        status = _read_json(status_path)
        problem_path = problem_dir / "problem.json"
        problem = _read_json(problem_path) if problem_path.is_file() else {}
        tests_path = problem_dir / "tests.jsonl"
        tests_count = sum(1 for line in tests_path.read_text(encoding="utf-8").splitlines() if line.strip()) if tests_path.is_file() else 0
        problem_id = status.get("problem_id", problem_dir.name)
        rows.append({"id": problem_id, "status": status, "problem": problem, "test_count": tests_count, "directory": problem_dir, "sample_conflict": conflicts.get(problem_id)})
    return rows


def _escape(text: object) -> str:
    return str(text if text is not None else "—").replace("|", "\\|").replace("\n", " ")


def _summaries(rows: list[dict[str, Any]]) -> tuple[Counter[str], Counter[str], Counter[str]]:
    statuses: Counter[str] = Counter()
    reasons: Counter[str] = Counter()
    rejected_reasons: Counter[str] = Counter()
    for row in rows:
        admission = row["status"]
        state = str(admission.get("status", "pending"))
        reason = admission.get("reason") or "none"
        statuses[state] += 1
        reasons[str(reason)] += 1
        if state == "rejected":
            rejected_reasons[str(reason)] += 1
    return statuses, reasons, rejected_reasons


def render_dashboard(rows: list[dict[str, Any]]) -> str:
    statuses, reasons, _ = _summaries(rows)
    lines = [
        "# Waterloo CCO Admission Dashboard",
        "",
        "<!-- Generated by code/cco-eval/build_dashboard.py. Do not edit. -->",
        "",
        "## Counts",
        "",
        "| Status | Count |",
        "|---|---:|",
    ]
    for state in ("admitted", "rejected", "pending"):
        lines.append(f"| {state} | {statuses[state]} |")
    lines.extend(["", "| Reason | Count |", "|---|---:|"])
    for reason, count in sorted(reasons.items()):
        lines.append(f"| {reason} | {count} |")
    lines.extend(
        [
            "",
            "## Problems",
            "",
            "| ID | Year | Title | Status | Reason | Grading kind | Subtasks | Tests | Time limit (s) | Worker model | Notes |",
            "|---|---:|---|---|---|---|---:|---:|---:|---|---|",
        ]
    )
    for row in sorted(rows, key=lambda item: item["id"]):
        problem = row["problem"]
        admission = row["status"]
        notes_path = row["directory"] / "notes.md"
        note_parts = [f"[{row['id']}/notes.md](problems/{row['id']}/notes.md)"] if notes_path.is_file() else []
        if row.get("sample_conflict"):
            note_parts.append(f"sample conflict: {_escape(row['sample_conflict'])}")
        notes = "; ".join(note_parts) if note_parts else "—"
        subtask_count = len(problem.get("subtasks", []))
        lines.append(
            "| "
            + " | ".join(
                (
                    _escape(row["id"]),
                    _escape(problem.get("year")),
                    _escape(problem.get("title")),
                    _escape(admission.get("status")),
                    _escape(admission.get("reason")),
                    _escape(problem.get("grading_kind")),
                    str(subtask_count),
                    str(row["test_count"]),
                    _escape(problem.get("time_limit_s")),
                    _escape(admission.get("worker_model")),
                    notes,
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def _main_admitted_count() -> int:
    try:
        result = subprocess.run(
            ["git", "show", f"main:{DASHBOARD_PATH}"],
            cwd=ROOT,
            text=True,
            capture_output=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return 0
    table_rows = re.findall(r"(?m)^\|\s*cco-[^|]+\|[^|]*\|[^|]*\|\s*admitted\s*\|", result.stdout)
    if table_rows:
        return len(table_rows)
    count = re.search(r"(?m)^\|\s*admitted\s*\|\s*(\d+)\s*\|", result.stdout)
    return int(count.group(1)) if count else 0


def metric_line(rows: list[dict[str, Any]], baseline_admitted: int) -> str:
    statuses, _, rejected_reasons = _summaries(rows)
    reasons = ",".join(f"{reason}={count}" for reason, count in sorted(rejected_reasons.items()))
    return (
        f"waterloo-suite admitted={statuses['admitted']} rejected={statuses['rejected']} ({reasons}) "
        f"pending={statuses['pending']} delta_vs_main={statuses['admitted'] - baseline_admitted:+d}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--problems-root", type=Path, default=DEFAULT_PROBLEMS)
    parser.add_argument("--dashboard", type=Path, default=DEFAULT_DASHBOARD)
    parser.add_argument("--metric", action="store_true")
    args = parser.parse_args()
    rows = _records(args.problems_root)
    args.dashboard.parent.mkdir(parents=True, exist_ok=True)
    args.dashboard.write_text(render_dashboard(rows), encoding="utf-8")
    if args.metric:
        print(metric_line(rows, _main_admitted_count()))


if __name__ == "__main__":
    main()
